def _run_time(slug: str) -> str:
    """The row's run time, measured off the rendered MP3 rather than claimed.

    The scripts used to open with a hand-written "Run time about N minutes",
    which was a placeholder and read 8 to 12 minutes against audio that runs
    under four - the figure described the exercise, pauses and all, not the
    track. Measuring the file is the only version that cannot drift: re-render
    at a different speaking rate and this follows it. No MP3 yet (a text-only
    build, or before the first render) returns "" and the caller falls back to
    the goal sentence, so nothing claims a run time it cannot back up.
    """
    mp3 = REPO / "assets" / "audio" / "mental-training" / ("%s.mp3" % slug)
    if not mp3.exists():
        return ""
    secs = tts.mp3_duration(mp3.read_bytes())
    return "Run time %d:%02d" % (int(secs // 60), int(secs % 60))


def _sessions() -> list[dict]:
    """The six session scripts, plus the intro, straight from the markdown."""
    out = []
    for md in sorted(SESSION_DIR.glob("*.md")):
        text = md.read_text(encoding="utf-8")
        m = re.search(r"^#\s+(.+)$", text, re.M)
        title = m.group(1).strip() if m else md.stem
        # The row's subtitle is the measured run time. Failing that - no audio
        # built yet - it is the first sentence of the lead paragraph, which is
        # the session's goal.
        body = re.sub(r"^#\s+.+$", "", text, count=1, flags=re.M).strip()
        first = body.split("\n\n")[0].replace("\n", " ").strip()
        sub = _run_time(md.stem) or (first.split(". ")[0].strip(" .")
                                     if first else "")
        out.append({
            "slug": md.stem,
            "title": title,
            "sub": sub,
            "intro": md.stem == INTRO_SLUG,
            "audio": "assets/audio/mental-training/%s.mp3" % md.stem,
            "text": text,
        })
    return out


def inject(courses: list[dict]) -> None:
    """Write the Mental Training text into index.html between the markers.

    The hub is one self-contained file that has to work with no network, so the
    session scripts and the walkthrough text live in the page rather than
    behind a fetch. Only the audio needs the network, and each player removes
    itself when its file is not there - which is the state until the render
    runs on a box with credentials.
    """
    payload = {
        "sessions": _sessions(),
        "courses": [{
            "slug": c["slug"], "course": c["course"], "tees": c["tees"],
            "holes": [{"hole": h["hole"], "par": h["par"],
                       "yardage": h["yardage"], "audio": h["audio"],
                       "text": h["text"]}
                      for h in c["holes"]],
        } for c in courses],
    }

    block = "%s\n  var MENTAL_TRAINING=%s;\n%s" % (
        BEGIN, json.dumps(payload, separators=(",", ":")), END)

    src = INDEX.read_text(encoding="utf-8")
    if BEGIN in src and END in src:
        start, stop = src.index(BEGIN), src.index(END) + len(END)
        src = src[:start] + block + src[stop:]
    else:
        raise SystemExit(
            "index.html has no MENTAL-TRAINING:BEGIN / END markers - add them "
            "inside the app script before running with injection")
    INDEX.write_text(src, encoding="utf-8")
    holes = sum(len(c["holes"]) for c in payload["courses"])
    print("\nbaked %d sessions and %d holes across %d courses into index.html "
          "(%.0f KB)" % (len(payload["sessions"]), holes,
                         len(payload["courses"]), len(block) / 1024))


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("slugs", nargs="*", help="course slugs; default is all")
    ap.add_argument("--no-audio", action="store_true",
                    help="write text and manifest only, skip the TTS render")
    ap.add_argument("--no-inject", action="store_true",
                    help="do not touch index.html")
    ap.add_argument("--force", action="store_true",
                    help="re-render audio even when the script is unchanged")
    args = ap.parse_args(argv[1:])

    slugs = args.slugs or sorted(p.stem for p in COURSE_DIR.glob("*.json"))
    if not slugs:
        print("no course JSON in %s - run scripts/extract_course_holes.py first"
              % COURSE_DIR)
        return 1

    built, all_gaps = [], {}
    for slug in slugs:
        print("%s" % slug)
        course, gaps = build_course(slug, not args.no_audio, args.force)
        built.append(course)
        all_gaps[slug] = gaps
        print("   %d holes written to %s"
              % (len(course["holes"]), (TEXT_DIR / slug).relative_to(REPO)))

    if not args.no_inject:
        inject(built)

    print("\nGAPS - fields the pipeline could not resolve, left empty rather "
          "than filled in:")
    for slug, gaps in all_gaps.items():
        if not gaps:
            print("  %s: none" % slug)
            continue
        byfield: dict[str, list[int]] = {}
        for field, n in gaps:
            byfield.setdefault(field, []).append(n)
        for field in ("shape", "trouble", "green_notes"):
            holes = byfield.get(field)
            if not holes:
                continue
            print("  %s: %s missing on %d hole%s (%s)"
                  % (slug, field, len(holes), "" if len(holes) == 1 else "s",
                     ", ".join(str(h) for h in holes)))

    if args.no_audio:
        total = 0
    else:
        total = sum(p.stat().st_size for p in AUDIO_ROOT.rglob("*.mp3"))
    print("\nwalkthrough audio total: %.1f MB" % (total / 1e6))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
